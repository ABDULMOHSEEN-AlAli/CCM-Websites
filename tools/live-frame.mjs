// Capture the live page around a design, so previews show inside the real site.
//
//   node tools/live-frame.mjs CCM/pages/dean-chairmen
//       → reads <meta name="ccm-live-url"> from the page's options, fetches that
//         live page and writes CCM/pages/dean-chairmen/live-frame.js
//   node tools/live-frame.mjs CCM/pages/home https://ccm.kfupm.edu.sa/home
//       → the same, with the live address given directly
//
// Where the design goes: by default inside the page's content column (beside
// the side menu). An option with <meta name="ccm-live-section" content="News,Events">
// replaces a whole band of the page instead: the part that holds those
// placeholders (pages without a content column, like the home page).
// content="main" replaces everything between the header and the footer
// (a whole new home page).
//
// live-frame.js holds the live header, breadcrumb, side menu and footer (scripts
// removed, links made absolute). design-system/preview.js puts each option's
// content into the live content column. PREVIEW ONLY: never uploaded.
// Run it once per page, and again if the live header, menu or footer change.

import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { fetchLive, splitAtContent, splitAtSection, splitAtMain } from './lib/live-page.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const sectionArg = args.find((a) => a.startsWith('--section='))?.slice('--section='.length);
const [target, urlArg] = args.filter((a) => !a.startsWith('--'));
if (!target) {
  console.error('Usage: node tools/live-frame.mjs <SITE/pages/page-folder> [live page address]');
  process.exit(1);
}
const dir = path.resolve(ROOT, target);
if (!statSync(dir).isDirectory()) throw new Error(`${target} is not a folder`);

let url = urlArg;
let section = sectionArg;
for (const f of readdirSync(dir).filter((f) => f.endsWith('.html') && f !== 'index.html').sort()) {
  const page = readFileSync(path.join(dir, f), 'utf8');
  url ??= page.match(/<meta\s+name="ccm-live-url"\s+content="([^"]+)"/)?.[1];
  section ??= page.match(/<meta\s+name="ccm-live-section"\s+content="([^"]+)"/)?.[1];
}
if (!url) throw new Error(`No <meta name="ccm-live-url"> in the options in ${target}. Give the address as a second argument.`);

const { origin } = new URL(url);
const html = await fetchLive(url);
const head = html.slice(0, html.search(/<body\b/i));
let { before, after } = section === 'main' ? splitAtMain(html) : section ? splitAtSection(html, section) : splitAtContent(html);

// Body only: from just after <body> to just before </body>.
before = before.slice(before.indexOf('>', before.search(/<body\b/i)) + 1);
after = after.slice(0, after.search(/<\/body>/i));

const clean = (s) => s
  .replace(/<script\b[\s\S]*?<\/script>/gi, '')       // no analytics or theme scripts in a preview
  .replace(/<noscript\b[\s\S]*?<\/noscript>/gi, '')
  .replace(/<!--[\s\S]*?-->/g, '')
  .replace(/<i\b[^>]*class="[^"]*\bfa[srb]?\b[^"]*"[^>]*>\s*<\/i>/gi, '') // Font Awesome shows as boxes in local files
  .replace(/\s(src|href)="\/(?!\/)/g, ` $1="${origin}/`) // links to the live site
  .replace(/\s(src|href)="(?![a-z]+:|\/\/|#)([^"]+)"/gi, (m, a, v) => ` ${a}="${new URL(v, url).href}"`)
  .replace(/\s+\n/g, '\n')
  .replace(/\n{2,}/g, '\n')
  .replace(/[ \t]{2,}/g, ' ');

// The live theme's stylesheets, in their order (preview.js adds any the option page lacks).
const styles = [...head.matchAll(/<link\b[^>]*rel="stylesheet"[^>]*>/gi)]
  .map((m) => m[0].match(/href="([^"]+)"/)?.[1])
  .filter(Boolean)
  .map((h) => new URL(h, url).href);

const frame = { url, section: section ?? 'Content', date: new Date().toISOString().slice(0, 10), styles, before: clean(before), after: clean(after) };
const out = path.join(dir, 'live-frame.js');
writeFileSync(out,
  `// GENERATED by tools/live-frame.mjs from ${url} on ${frame.date}. Do not edit.\n` +
  `// PREVIEW ONLY: the live header, breadcrumb, side menu and footer around the design.\n` +
  `// Never uploaded. To refresh: node tools/live-frame.mjs ${path.relative(ROOT, dir).split(path.sep).join('/')}\n` +
  `window.CCM_LIVE_FRAME = ${JSON.stringify(frame)};\n`);

console.log(`${path.relative(ROOT, out).split(path.sep).join('/')}  (${(Buffer.byteLength(frame.before + frame.after) / 1024).toFixed(1)} KB of live page from ${url}; ` +
  `the design replaces ${section === 'main' ? 'everything between the header and the footer' : section ? `the band holding ${section}` : 'the content column'})`);
console.log(`Theme stylesheets: ${styles.length}. Options in this folder load it with <script src="live-frame.js" defer></script>.`);
